import { readFileSync, writeFileSync } from 'node:fs';
const source = JSON.parse(readFileSync('apps/web/src/ui/tokens/source.json', 'utf8'));
// Derived interactive colors are never separately editable.
const shade = (hex, black) =>
  '#' +
  hex
    .slice(1)
    .match(/../g)
    .map((v) =>
      Math.round(parseInt(v, 16) * (1 - black))
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')
    .toUpperCase();
for (const preset of Object.values(source.presets))
  for (const mode of Object.values(preset.modes)) {
    mode.accentHover = shade(mode.accent, 0.12);
    mode.accentActive = shade(mode.accent, 0.24);
    mode.selectionForeground = mode.accentHover;
  }
source.modes = source.presets.sage.modes; // Default CSS fallback, not a second source.
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const lines = (values) =>
  Object.entries(values)
    .map(([k, v]) => `  --vn-${kebab(k)}: ${v};`)
    .join('\n');
const sizes = {};
for (const group of ['radiusPx', 'targetPx', 'rowMinPx', 'layoutPx'])
  for (const [k, v] of Object.entries(source[group]))
    sizes[`${group.replace('Px', '')}-${k}`] = `${v}px`;
source.spacingPx.forEach((v) => (sizes[`space-${v}`] = `${v}px`));
const type = source.typography;
for (const [k, v] of Object.entries(type))
  if (typeof v !== 'object') sizes[`type-${k.replace('Px', '')}`] = k.endsWith('Px') ? `${v}px` : v;
Object.assign(sizes, {
  'motion-fast': `${source.motion.fastMs}ms`,
  'motion-base': `${source.motion.baseMs}ms`,
  'motion-easing': source.motion.easing,
  'focus-width': `${source.focus.widthPx}px`,
  'focus-offset': `${source.focus.offsetPx}px`,
});
let css = `/* Generated by scripts/ui/tokens.mjs. Edit source.json only. */\n[data-acornary-mode] {\n${lines({ ...source.semantic, ...sizes })}\n  color-scheme: light;\n}\n`;
for (const [mode, values] of Object.entries(source.modes))
  css += `[data-acornary-mode="${mode}"] {\n${lines(values)}\n  --vn-body-size: var(--vn-type-${mode}-body);\n  --vn-row-min: var(--vn-row-min-${mode === 'daily' ? 'daily' : 'management-desktop'});\n}\n`;
for (const [preset, spec] of Object.entries(source.presets ?? {}))
  for (const [mode, values] of Object.entries(spec.modes)) {
    css += `[data-acornary-preset="${preset}"][data-acornary-mode="${mode}"] {\n${lines(values)}\n}\n`;
  }
css +=
  '@media (prefers-reduced-motion: reduce) { [data-acornary-mode] { --vn-motion-fast: 0ms; --vn-motion-base: 0ms; } }\n';
const candidate = Object.fromEntries(Object.entries(source).filter(([k]) => k !== 'legacy'));
for (const [path, content] of [
  ['apps/web/src/ui/theme/tokens.generated.css', css],
  ['docs/ux-vnext/design-tokens.json', JSON.stringify(candidate, null, 2) + '\n'],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) throw Error(`Stale generated file: ${path}`);
  } else writeFileSync(path, content);
}
console.log('Token sources and generated outputs are consistent.');
// Enforce readable text pairs across both modes, including every primary state.
const luminance = (hex) => {
  const rgb = hex
    .slice(1)
    .match(/../g)
    .map((v) => parseInt(v, 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722;
};
for (const [mode, colors] of Object.entries(
  Object.fromEntries(
    Object.entries(source.presets ?? {}).flatMap(([p, s]) =>
      Object.entries(s.modes).map(([m, v]) => [`${p}/${m}`, v]),
    ),
  ),
)) {
  const pairs = [
    ['foreground', 'background'],
    ['mutedForeground', 'background'],
    ['accentForeground', 'accent'],
    ['accentForeground', 'accentHover'],
    ['accentForeground', 'accentActive'],
    ['selectionForeground', 'selection'],
  ];
  for (const [fg, bg] of pairs) {
    const a = luminance(colors[fg]),
      b = luminance(colors[bg]);
    const contrast = (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
    if (contrast < 4.5) throw Error(`${mode} ${fg}/${bg}: ${contrast.toFixed(2)} < 4.5`);
  }
}
console.log('Text contrast pairs meet 4.5:1 in both modes.');
